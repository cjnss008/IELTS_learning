'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const source = fs.readFileSync(path.join(root, '开始学习.html'), 'utf8');
const take = name => JSON.parse(source.match(new RegExp('^const ' + name + '=(.*);\\r?$', 'm'))[1]);
const lessons = take('LESSONS'), vocab = take('VOCAB');
const data = {
  lessons: lessons.map(({ day, title, cn, text, grammar, grammarQuiz, S }) => ({ day, title, cn, text, grammar, grammarQuiz, S })),
  vocab: Object.entries(vocab).flatMap(([day, cards]) => cards.map((v, i) => ({ ...v, day: Number(day), id: `d${day}-v${i}` })))
};
fs.writeFileSync(path.join(root, 'assets/course-data.js'), '/* Generated by tools/generate-course-data.cjs from existing course content. */\n(function(root){const data=' + JSON.stringify(data) + ';if(typeof module!=="undefined"&&module.exports)module.exports=data;root.IELTSCourse=data;})(globalThis);\n');
console.log(`Generated ${data.lessons.length} lessons and ${data.vocab.length} vocabulary cards.`);
