"""Pre-generate course vocabulary audio; authoring requires edge-tts, ffmpeg and ffprobe."""
import argparse, asyncio, hashlib, json, os, re, shutil, subprocess, time
from pathlib import Path
import edge_tts
ROOT=Path(__file__).resolve().parent.parent
OUT=ROOT/'audio'/'vocabulary'
META=OUT/'metadata'
MAPPING=ROOT/'assets'/'vocabulary-audio.js'
VOICE='en-GB-SoniaNeural'
RATE='-10%'
FLAGS=0x08000000 if os.name=='nt' else 0

def read_data(path):
    raw=path.read_text(encoding='utf-8');start=raw.index('const data=')+len('const data=')
    return json.JSONDecoder().raw_decode(raw[start:])[0]
def key(word):return re.sub(r'\s+',' ',word.strip()).lower()
def digest(value):return hashlib.sha256(value.encode('utf-8')).hexdigest()
def configuration(word):return digest(json.dumps({'text':word,'voice':VOICE,'rate':RATE,'format':'mp3-24000-mono-48k'},sort_keys=True,ensure_ascii=False))
def filenames(word):
    slug=re.sub(r'[^a-z0-9]+','-',key(word)).strip('-')[:55] or 'word'
    name=slug+'-'+digest(key(word))[:10]
    return OUT/(name+'.mp3'),META/(name+'.json')
def probe(path):
    if not path.is_file() or path.stat().st_size<500:return None
    try:
        value=json.loads(subprocess.check_output(['ffprobe','-v','error','-show_entries','format=duration:stream=codec_name','-of','json',str(path)],stderr=subprocess.DEVNULL,creationflags=FLAGS))
        duration=float(value['format']['duration'])
        if .1<=duration<=30 and any(stream.get('codec_name')=='mp3' for stream in value.get('streams',[])):return duration
    except (OSError,ValueError,KeyError,subprocess.SubprocessError):pass
    return None

def inventory():
    data=read_data(ROOT/'assets'/'curriculum-data.js');course=read_data(ROOT/'assets'/'course-data.js')
    words={}
    for material in data['materials']:
        if material.get('type')=='vocabulary':
            for item in material.get('vocabulary',[]):words.setdefault(key(item['word']),item['word'].strip())
    existing={key(item['word']):item['audio'] for item in course.get('vocab',[]) if item.get('audio')}
    day=data['days'][0];ids={mid for task in day['tasks'] if task['id']=='vocabulary' for mid in task['materialIds']}
    first={key(item['word']) for material in data['materials'] if material['id'] in ids for item in material.get('vocabulary',[])}
    return words,existing,first

def emit_mapping(items):
    data={'schema':1,'voice':VOICE,'rate':RATE,'count':len(items),'items':dict(sorted(items.items()))}
    content="/* Generated by tools/synthesize-vocabulary.py; verified local MP3 files only. */\n(function(root){'use strict';const data="+json.dumps(data,ensure_ascii=False,separators=(',',':')).replace('<','\\u003c')+";root.IELTSVocabularyAudio=data;if(typeof module==='object'&&module.exports)module.exports=data;})(typeof globalThis!=='undefined'?globalThis:this);\n"
    temporary=MAPPING.with_suffix('.js.tmp');temporary.write_bytes(content.encode('utf-8'))
    for attempt in range(10):
        try:
            os.replace(temporary,MAPPING);break
        except PermissionError:
            if attempt==9:raise
            time.sleep(min(.04*(2**attempt),.5))

async def main(args):
    OUT.mkdir(parents=True,exist_ok=True);META.mkdir(parents=True,exist_ok=True);args.work_dir.mkdir(parents=True,exist_ok=True)
    words,existing,first=inventory();selected={k:v for k,v in words.items() if not args.first_day or k in first};items={}
    if MAPPING.exists():
        try:items={k:v for k,v in read_data(MAPPING).get('items',{}).items() if k in words}
        except (ValueError,KeyError):pass
    semaphore=asyncio.Semaphore(args.concurrency);started=time.time();stats={'ready':0,'cached':0,'reused':0,'failed':0};errors=[];finished=0
    async def generate(k,word):
        nonlocal finished
        async with semaphore:
            target,meta=filenames(word);config_hash=configuration(word)
            try:
                original=existing.get(k)
                if original and re.fullmatch(r'audio/words/[A-Za-z0-9._-]+\.mp3',original) and '..' not in original:
                    duration=await asyncio.to_thread(probe,ROOT/original)
                    if duration:
                        items[k]={'audio':original,'durationSeconds':duration,'textHash':digest(word),'audioHash':hashlib.sha256((ROOT/original).read_bytes()).hexdigest(),'source':'existing','synthetic':True};stats['reused']+=1;return
                if target.exists() and meta.exists():
                    try:old=json.loads(meta.read_text(encoding='utf-8'))
                    except ValueError:old={}
                    if old.get('configurationHash')==config_hash:
                        duration=await asyncio.to_thread(probe,target)
                        if duration:
                            items[k]={'audio':target.relative_to(ROOT).as_posix(),'durationSeconds':duration,'textHash':digest(word),'audioHash':hashlib.sha256(target.read_bytes()).hexdigest(),'source':'generated','synthetic':True};stats['cached']+=1;return
                part=args.work_dir/(target.stem+'-raw.mp3');normalized=args.work_dir/(target.stem+'-verified.mp3')
                for attempt in range(4):
                    try:
                        await edge_tts.Communicate(word,voice=VOICE,rate=RATE,connect_timeout=20,receive_timeout=60).save(str(part))
                        await asyncio.to_thread(subprocess.run,['ffmpeg','-hide_banner','-loglevel','error','-y','-i',str(part),'-ar','24000','-ac','1','-b:a','48k',str(normalized)],check=True,capture_output=True,creationflags=FLAGS)
                        duration=await asyncio.to_thread(probe,normalized)
                        if not duration:raise RuntimeError('Synthesized MP3 failed ffprobe verification')
                        break
                    except Exception:
                        if attempt==3:raise
                        await asyncio.sleep(2**attempt)
                incoming=target.with_suffix(".mp3.tmp")
                await asyncio.to_thread(shutil.copyfile,normalized,incoming)
                os.replace(incoming,target)
                normalized.unlink(missing_ok=True)
                metadata={'word':word,'textHash':digest(word),'configurationHash':config_hash,'voice':VOICE,'rate':RATE,'durationSeconds':duration,'audioHash':hashlib.sha256(target.read_bytes()).hexdigest(),'synthetic':True,'provider':'Microsoft online TTS via edge-tts','note':'学习词与词组的合成示范读音，不是专业发音评分。'}
                meta.write_bytes((json.dumps(metadata,ensure_ascii=False,indent=2)+'\n').encode('utf-8'))
                part.unlink(missing_ok=True)
                items[k]={'audio':target.relative_to(ROOT).as_posix(),'durationSeconds':duration,'textHash':digest(word),'audioHash':hashlib.sha256(target.read_bytes()).hexdigest(),'source':'generated','synthetic':True};stats['ready']+=1
            except Exception as error:
                items.pop(k,None);stats['failed']+=1;errors.append({'word':word,'error':type(error).__name__+': '+str(error)[:120]})
            finally:
                finished+=1
                if args.first_day or finished%10==0 or finished==len(selected):emit_mapping(items)
                if args.first_day or finished%10==0 or finished==len(selected):print(json.dumps({'progress':finished,'total':len(selected),'mapped':len(items),**stats,'elapsedSeconds':round(time.time()-started)},ensure_ascii=False),flush=True)
    print(json.dumps({'unique':len(words),'selected':len(selected),'reusable':sum(k in existing for k in selected),'concurrency':args.concurrency,'firstDay':args.first_day}),flush=True)
    await asyncio.gather(*(generate(k,word) for k,word in selected.items()))
    print(json.dumps({'complete':not errors,'selected':len(selected),'mapped':len(items),**stats,'elapsedSeconds':round(time.time()-started),'errors':errors},ensure_ascii=False),flush=True)
    if errors:raise SystemExit(1)

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--first-day',action='store_true');parser.add_argument('--concurrency',type=int,default=6);parser.add_argument('--work-dir',type=Path,default=ROOT/'work'/'vocabulary_hover-tts');args=parser.parse_args()
    if not 1<=args.concurrency<=12:parser.error('--concurrency must be 1–12')
    asyncio.run(main(args))
